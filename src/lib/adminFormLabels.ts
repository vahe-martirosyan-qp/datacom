const PROJECT_FIELD_LABELS: Record<string, string> = {
  title: "Название проекта",
  location: "Локация / город",
  year: "Год",
  heroImage: "URL изображения (герой)",
  bodyHtml: "Текст страницы (HTML, редактор ниже)",
  equipment: "Оборудование (JSON-массив строк)",
};

export function adminFormLabel(key: string): string {
  if (ADMIN_FORM_LABELS[key]) {
    return ADMIN_FORM_LABELS[key];
  }
  const m = key.match(/^project\.[^.]+\.([a-zA-Z]+)$/);
  if (m?.[1] && PROJECT_FIELD_LABELS[m[1]]) {
    return PROJECT_FIELD_LABELS[m[1]];
  }
  const b = key.match(/^blog\.[^.]+\.([a-zA-Z.]+)$/);
  if (b?.[1] && PROJECT_FIELD_LABELS[b[1]]) {
    return PROJECT_FIELD_LABELS[b[1]];
  }
  const ep = key.match(/^equipment\.product\.[^.]+\.[^.]+\.([a-zA-Z.]+)$/);
  if (ep?.[1]) {
    const field = ep[1];
    if (field === "images") {
      return "Галерея (слайдер)";
    }
    if (field === "orderLabel") {
      return "Текст кнопки «Заказать»";
    }
    if (field === "orderHref") {
      return "Ссылка «Заказать»";
    }
    if (field === "highlights") {
      return "Пункты (+)";
    }
    if (PROJECT_FIELD_LABELS[field]) {
      return PROJECT_FIELD_LABELS[field];
    }
  }
  const e = key.match(/^equipment\.[^.]+\.([a-zA-Z.]+)$/);
  if (e?.[1]) {
    const field = e[1];
    if (field === "seo.title") {
      return "SEO title";
    }
    if (field === "seo.description") {
      return "SEO description";
    }
    if (field === "eyebrow") {
      return "Подпись над H1";
    }
    if (field === "productsTitle") {
      return "Заголовок блока «Решения в категории»";
    }
    if (field === "specsTitle") {
      return "Заголовок блока характеристик";
    }
    if (field === "ctaLabel") {
      return "Текст кнопки консультации";
    }
    if (field === "ctaHref") {
      return "Ссылка кнопки (например contacts)";
    }
    if (field === "pdfLabel") {
      return "Текст ссылки на PDF";
    }
    if (field === "pdfHref") {
      return "URL PDF";
    }
    if (field === "backLabel") {
      return "Текст ссылки «назад» на /equipment";
    }
    if (field === "highlights") {
      return "Быстрые пункты (+)";
    }
    if (field === "products") {
      return "Товары в блоке «Решения в категории»";
    }
    if (PROJECT_FIELD_LABELS[field]) {
      return PROJECT_FIELD_LABELS[field];
    }
  }
  return key;
}
